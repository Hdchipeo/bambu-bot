#!/usr/bin/env python3
"""Pack simulator --export-coffee geometry into a dependency-free RGB565 clip.
Run: python3 scripts/generate_coffee_clip.py /tmp/bambu-coffee-frames
No telemetry or private configuration is read. Assets are reproducible.
"""
from collections import Counter
from pathlib import Path
import argparse
import struct
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]

def read_bmp(path):
    data = path.read_bytes()
    offset = struct.unpack_from('<I', data, 10)[0]
    w, h, planes, bits = struct.unpack_from('<iiHH', data, 18)
    assert (w, abs(h), planes) == (280, 240, 1) and bits in (24, 32)
    pixel_bytes = bits // 8
    stride = (w * pixel_bytes + 3) & ~3
    rows = [data[offset+y*stride:offset+(y+1)*stride] for y in range(abs(h))]
    if h > 0:
        rows.reverse()
    return [((row[x+2] >> 3) << 11) | ((row[x+1] >> 2) << 5) | (row[x] >> 3)
            for row in rows for x in range(0, w*pixel_bytes, pixel_bytes)]

def pack(indices):
    """PackBits: high bit = repeat, low 7 bits + 1 = count; otherwise literal."""
    out = bytearray()
    i = 0
    while i < len(indices):
        run = 1
        while i+run < len(indices) and run < 128 and indices[i+run] == indices[i]:
            run += 1
        if run >= 3:
            out.extend((0x80 | (run-1), indices[i]))
            i += run
        else:
            start = i
            i += 1
            while i < len(indices) and i-start < 128:
                if i+2 < len(indices) and indices[i] == indices[i+1] == indices[i+2]:
                    break
                i += 1
            out.append(i-start-1)
            out.extend(indices[start:i])
    return out

def rgb(c):
    return ((c >> 11)*255/31, ((c >> 5)&63)*255/63, (c&31)*255/31)

def array(name, typename, values, columns=24):
    lines = [f'inline constexpr {typename} {name}[] = {{']
    lines += ['    '+','.join(str(v) for v in values[i:i+columns])+',' for i in range(0,len(values),columns)]
    return '\n'.join(lines+['};'])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('frames', type=Path)
    args = parser.parse_args()
    all_frames = [[read_bmp(args.frames/f'{theme}-{i:03d}.bmp') for i in range(150)] for theme in ('black','green')]
    xs, ys = [], []
    for frames in all_frames:
        for frame in frames:
            bg = frame[0]
            for i, c in enumerate(frame):
                if c != bg:
                    xs.append(i%280); ys.append(i//280)
    x0, y0, x1, y1 = max(0,min(xs)-2), max(0,min(ys)-2), min(280,max(xs)+3), min(240,max(ys)+3)
    # These bounds must leave both native LVGL labels and telemetry outside the clip.
    assert y0 >= 45 and y1 <= 196, (x0,y0,x1,y1)
    w,h = x1-x0,y1-y0
    palettes, offsets, stream = [], [0], bytearray()
    digest = hashlib.sha256()
    max_error = 0
    for frames in all_frames:
        cropped = [[c for y in range(y0,y1) for c in frame[y*280+x0:y*280+x1]] for frame in frames]
        counts = Counter(c for frame in cropped for c in frame)
        # Preserve frequent flat colors, then cover rare highlights/antialiased edges.
        palette = [c for c,_ in counts.most_common(128)]
        candidates = {c: rgb(c) for c in counts if c not in palette}
        distance = {c: min(sum((a-b)**2 for a,b in zip(value,rgb(p))) for p in palette)
                    for c,value in candidates.items()}
        while len(palette) < 256 and distance:
            selected = max(distance, key=distance.get)
            palette.append(selected)
            value = candidates[selected]
            del distance[selected]
            for c in distance:
                distance[c] = min(distance[c],sum((a-b)**2 for a,b in zip(candidates[c],value)))
        colors = [rgb(c) for c in palette]
        mapping = {}
        for c in counts:
            r,g,b = rgb(c)
            best = min(range(len(palette)),key=lambda i:sum((a-v)**2 for a,v in zip((r,g,b),colors[i])))
            mapping[c] = best
            max_error = max(max_error, max(abs(a-v) for a,v in zip((r,g,b),colors[best])))
        palettes.extend(palette+[0]*(256-len(palette)))
        for frame in cropped:
            indices = bytes(mapping[c] for c in frame)
            digest.update(indices)
            stream.extend(pack(indices));offsets.append(len(stream))
    dest = ROOT/'ui/assets'
    dest.mkdir(exist_ok=True)
    text = '// Generated by scripts/generate_coffee_clip.py. Do not edit.\n'
    text += 'namespace bambu::ui::coffee_data {\n'
    text += f'inline constexpr int kX={x0}, kY={y0}, kWidth={w}, kHeight={h};\n'
    text += array('kPalette','uint16_t',palettes)+'\n'
    text += array('kOffsets','uint32_t',offsets)+'\n'
    text += array('kStream','uint8_t',stream)+'\n}\n'
    (dest/'coffee_clip.inc').write_text(text)
    manifest = dict(format='palette RGB565 + PackBits indices',width=w,height=h,x=x0,y=y0,
                    themes=2,frames_per_theme=150,intro_frames=24,loop_frames=126,frame_ms=50,
                    flash_bytes=len(stream)+len(offsets)*4+len(palettes)*2,
                    double_buffer_bytes=w*h*4,max_palette_channel_error=round(max_error,2),
                    decoded_index_sha256=digest.hexdigest())
    (dest/'coffee_clip.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))

if __name__ == '__main__':
    main()
